#!/usr/bin/env python3
"""Generate proof/ZZN/LookGen/NWxH.lean: per box, the slice table and witness theorems.

Reads the existing certificate modules proof/BoxKGen/NWxH/{S*,Main}.lean and restates each
`gK : SliceGood ...` as `gwK : SliceW ...` through `sliceCOK_wit`, reusing `baseB` and `slK`.
"""
import os, re, glob
root = os.path.join(os.path.dirname(__file__), "..", "proof")
pat = re.compile(r"theorem g(\d+) : SliceGood (\d+) (\d+) d\d+\.1 := sliceCOK_sound \(by decide\) "
                 r"\(by decide\) \(by decide\) \(by decide\) (base\d+) \(subM_zero \([^)]*\)\) (sl\d+)")
HDR = """/-
SPDX-License-Identifier: CC0-1.0
Dedicated to the public domain under CC0 1.0 Universal; see LICENSE.
-/
module

public import BoxKGen.{box}.Main
public import ZZN.Look.Wit
public import ZZN.Look.Size

@[expose] public section

/-! Generated by notes/gen_lookgen.py: the slice table of box {box} and its witnesses. -/

set_option Elab.async false
set_option maxRecDepth 100000
namespace ZZN.LookGen.{box}
open ZZN ZZN.Cut ZZN.BoxK BoxKGen.{box}

"""
for d in sorted(glob.glob(os.path.join(root, "BoxKGen", "N*x*"))):
    box = os.path.basename(d)
    main = open(os.path.join(d, "Main.lean")).read()
    order = re.search(r"theorem rows : rowsOK \d+ \[([^\]]*)\]", main).group(1)
    names = [s.strip()[:-2] for s in order.split(",")]
    gw = {}
    for f in glob.glob(os.path.join(d, "S*.lean")):
        for m in pat.finditer(open(f).read()):
            k, w, h, base, sl = m.groups()
            gw["d" + k] = (w, h, base, sl, k)
    w, h = gw[names[0]][0], gw[names[0]][1]
    out = [HDR.format(box=box)]
    for n in names:
        _, _, base, sl, k = gw[n]
        out.append(f"theorem gw{k} : SliceW {w} {h} d{k}.1 d{k}.2.2.1 d{k}.2.2.2.2 := "
                   f"sliceCOK_wit (by decide) (by decide) (by decide) (by decide) {base} {sl}\n")
    out.append("\nnoncomputable def tab : List CData := [" + ", ".join(names) + "]\n")
    out.append(f"theorem tabRows : rowsOK {w} (tab.map (·.1)) = true := rows\n")
    out.append(f"theorem tabW : List.Forall (fun d : CData => SliceW {w} {h} d.1 d.2.2.1 d.2.2.2.2) tab :=\n  ⟨"
               + ", ".join("gw" + n[1:] for n in names) + "⟩\n")
    out.append("theorem tabSz : tab.all ZZN.Look.szOK = true := by decide +kernel\n")
    out.append("theorem tabLen : tab.length ≤ 1569 := by decide +kernel\n")
    out.append(f"\nend ZZN.LookGen.{box}\n")
    open(os.path.join(root, "ZZN", "LookGen", box + ".lean"), "w").write("".join(out))
    print(box, len(names))

# The table over all boxes and its certificate.
boxes = [(w, h) for w in range(11, 17) for h in range(w, 17)]
L = ["""/-
SPDX-License-Identifier: CC0-1.0
Dedicated to the public domain under CC0 1.0 Universal; see LICENSE.
-/
module

"""]
for w, h in boxes:
    L.append(f"public import ZZN.LookGen.N{w}x{h}\n")
L.append("""public import ZZN.Look.Leaf
public import ZZN.Look.LeafT

@[expose] public section

/-! Generated by notes/gen_lookgen.py: the slice tables of all boxes `11 ≤ w ≤ h ≤ 16`. -/

namespace ZZN.Look

open ZZN ZZN.BoxK

noncomputable def tabCore : ℕ → ℕ → List CData
""")
for w, h in boxes:
    L.append(f"  | {w}, {h} => ZZN.LookGen.N{w}x{h}.tab\n")
L.append("  | _, _ => []\n\n")
L.append("""/-- The slice table of the box `w × h`, empty unless `11 ≤ w ≤ h ≤ 16`. -/
noncomputable def tabAll (w h : ℕ) : List CData :=
  if 11 ≤ w ∧ w ≤ h ∧ h ≤ 16 then tabCore w h else []

theorem tabAll_ok : TabOK tabAll := by
  intro w h hw hwh hh
  have hw16 : w ≤ 16 := by omega
  unfold tabAll
  rw [ite_t ⟨hw, hwh, hh⟩]
  interval_cases w <;> interval_cases h
""")
for w, h in boxes:
    L.append(f"  · simp only [tabCore]; exact ⟨ZZN.LookGen.N{w}x{h}.tabRows, ZZN.LookGen.N{w}x{h}.tabW⟩\n")
L.append("""
theorem tabAll_sz : ZZN.T.TabSz tabAll := by
  intro w h
  unfold tabAll
  by_cases hc : 11 ≤ w ∧ w ≤ h ∧ h ≤ 16
  · rw [ite_t hc]
    obtain ⟨hw, hwh, hh⟩ := hc
    have hw16 : w ≤ 16 := by omega
    refine ⟨?_, ?_, fun _ => ⟨hw16, hh⟩⟩ <;> interval_cases w <;> interval_cases h
""")
for w, h in boxes:
    L.append(f"    · simp only [tabCore]; exact ZZN.LookGen.N{w}x{h}.tabSz\n")
for w, h in boxes:
    L.append(f"    · simp only [tabCore]; exact ZZN.LookGen.N{w}x{h}.tabLen\n")
L.append("""  · rw [ite_f hc]
    exact ⟨rfl, by simp, fun h => absurd rfl h⟩
""")
L.append("\nend ZZN.Look\n")
open(os.path.join(root, "ZZN", "Look", "Table.lean"), "w").write("".join(L))
