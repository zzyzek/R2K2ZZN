#!/usr/bin/env python3
"""Write gen/FinalK.lean: the characterization from the box certificates (BoxKGen) and the window
certificates (WinKU).

usage: gen_final.py [PREFIX]   box modules BoxKGen.{PREFIX}{w}x{h} (N for the gen_cbox boxes, as regen.sh uses)
"""
import os, sys
P = sys.argv[1] if len(sys.argv) > 1 else "B"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
boxes = [(w, h) for w in range(11, 17) for h in range(w, 17)]
out = ["-- generated by tools/gen_final.py", ""] + [f"import BoxKGen.{P}{w}x{h}.Main" for w, h in boxes]
out += ["import WinKU.Facts", "import ZZN.BoxK.None", "", "namespace ZZN", "",
        "theorem boxes_allK : ∀ w h, 11 ≤ w → w ≤ h → h ≤ 16 → BoxK.BoxCert w h := by",
        "  intro w h h1 h2 h3",
        "  have h4 : w ≤ 16 := by omega",
        "  interval_cases w <;> interval_cases h",
        "  exacts [" + ", ".join(f"BoxKGen.{P}{w}x{h}.box" for w, h in boxes) + "]", "",
        "/-- **Passing the catalogue is equivalent to solvability**, for both sides at least 11,",
        "with every finite fact checked by the kernel. -/",
        "theorem passes_iff_solvable_K (I : Inst) (hwf : I.WellFormed) (hw : 11 ≤ I.w) (hh : 11 ≤ I.h) :",
        "    Passes I ↔ Solvable I :=",
        "  ⟨fun hP => BoxK.theoremA_boxes boxes_allK BoxK.none_all I ⟨hw, hh, hwf⟩ hP,",
        "   WinKU.theoremB_K ⟨hw, hh, hwf⟩⟩", "", "end ZZN", "",
        "#print axioms ZZN.passes_iff_solvable_K", ""]
open(os.path.join(ROOT, 'gen', 'FinalK.lean' if P == 'B' else f'Final{P}.lean'), 'w').write('\n'.join(out))
print('wrote gen/Final', P)
