#!/usr/bin/env python3
"""Write Lean modules for Theorem A box certificates.

gen_box.py templates TEMPLATES_FILE          -> gen/BoxKGen/Templates.lean
gen_box.py box W H CERT_FILE [PER_FILE]     -> gen/BoxKGen/B{W}x{H}/S{n}.lean, Main.lean
CERT_FILE: lines SLICE a,b,c,d / PAIR k s / FIRE j / UNM ... (from split/slicecert.c)
"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, 'gen', 'BoxKGen')
AN = "abcdLH"

def node(toks, i):
    t = toks[i]
    if t == 'I':
        return "CTree.leaf", i + 1
    m = re.match(r'([HV])([abcdLH])([+-]\d+)\[(.*)\]$', t)
    vert = 'true' if m.group(1) == 'V' else 'false'
    pos = f"({AN.index(m.group(2))}, {int(m.group(3))})"
    ks = []
    for it in m.group(4).split(','):
        side = 'true' if it[1] == '1' else 'false'
        if it[0] == 's':
            ks.append(f"Kind.stay {side}")
        elif it[0] == 'c':
            mm = re.match(r'c[01]([abcdLH])([+-]\d+)$', it)
            ks.append(f"Kind.cross {side} ({AN.index(mm.group(1))}, {int(mm.group(2))})")
        else:
            mm = re.match(r'x[01]([abcdLH])([+-]\d+)([abcdLH])([+-]\d+)$', it)
            ks.append(f"Kind.exc {side} ({AN.index(mm.group(1))}, {int(mm.group(2))}) "
                      f"({AN.index(mm.group(3))}, {int(mm.group(4))})")
    l, i = node(toks, i + 1)
    r, i = node(toks, i)
    return f"(CTree.cut {vert} {pos} [{', '.join(ks)}] {l} {r})", i

def conv(line):
    return node(line.split(':', 1)[1].split(), 0)[0]

def sym(s):
    rx = s & 1; ry = (s >> 1) & 1; l = s >> 2; c = l & 1; a = (l >> 1) & 1; b = (l >> 2) & 1
    r0 = b if c else a; r1 = a if c else b
    B = lambda v: 'true' if v else 'false'
    return f"⟨false, {B(rx)}, {B(ry)}, {B(r0)}, {B(r1)}, {B(c)}⟩"

HDR = "-- generated by tools/gen_box.py\n"

def templates(path):
    os.makedirs(GEN, exist_ok=True)
    lines = open(path).readlines()
    out = [HDR, "import ZZN.BoxK.Box", "namespace BoxKGen", "open ZZN ZZN.Cut", ""]
    for k, l in enumerate(lines):
        out.append(f"def t{k} : CTree TPos := {conv(l)}")
    out.append("end BoxKGen")
    open(os.path.join(GEN, 'Templates.lean'), 'w').write('\n'.join(out) + '\n')
    print('templates', len(lines))

def box(w, h, cert, per):
    slices = []
    cur = None
    for line in open(cert):
        t = line.split()
        if not t: continue
        if t[0] == 'SLICE':
            cur = [t[1], [], []]; slices.append(cur)
        elif t[0] == 'PAIR':
            cur[1].append((int(t[1]), int(t[2])))
        elif t[0] == 'FIRE':
            cur[2].append(int(t[1]))
        elif t[0] == 'UNM':
            raise SystemExit(f'unmatched lane in slice {cur[0]}')
    name = f"B{w}x{h}"
    d = os.path.join(GEN, name); os.makedirs(d, exist_ok=True)
    ns = f"BoxKGen.{name}"
    nfiles = 0
    for f0 in range(0, len(slices), per):
        out = [HDR, "import BoxKGen.Templates", f"namespace {ns}", "open ZZN ZZN.Cut ZZN.BoxK BoxKGen", ""]
        for n in range(f0, min(f0 + per, len(slices))):
            xs, pairs, fires = slices[n]
            ps = ", ".join(f"(t{k}, {sym(s)})" for k, s in pairs)
            out.append(f"def c{n} : SliceData := (![{xs}], [{ps}], {fires})")
            out.append(f"theorem sl{n} : sliceOK {w} {h} c{n}.1 c{n}.2.1 c{n}.2.2 = true := by decide +kernel")
        out.append(f"end {ns}")
        open(os.path.join(d, f"S{f0 // per}.lean"), 'w').write('\n'.join(out) + '\n')
        nfiles += 1
    out = [HDR] + [f"import BoxKGen.{name}.S{i}" for i in range(nfiles)]
    out += [f"namespace {ns}", "open ZZN ZZN.Cut ZZN.BoxK BoxKGen", "",
            "set_option maxRecDepth 100000",
            "def certs : List SliceData := [" + ", ".join(f"c{n}" for n in range(len(slices))) + "]",
            f"theorem rows : rowsOK {w} (certs.map (·.1)) = true := by decide +kernel",
            f"theorem all : List.Forall (fun c : SliceData => sliceOK {w} {h} c.1 c.2.1 c.2.2 = true) certs :=",
            "  ⟨" + ", ".join(f"sl{n}" for n in range(len(slices))) + "⟩",
            f"theorem box : BoxCert {w} {h} := boxCert_of_certs certs rows all",
            f"end {ns}"]
    open(os.path.join(d, "Main.lean"), 'w').write('\n'.join(out) + '\n')
    print(name, 'slices', len(slices), 'files', nfiles)

if sys.argv[1] == 'templates':
    templates(sys.argv[2])
else:
    box(int(sys.argv[2]), int(sys.argv[3]), sys.argv[4], int(sys.argv[5]) if len(sys.argv) > 5 else 2)
